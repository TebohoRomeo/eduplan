-- Edulution admin session access SQL support
-- This file is intended to be used by the backend team to support:
-- 1) admin authentication with email + password
-- 2) fetching all sessions for admin-only access
-- 3) optional center-scoped session retrieval

CREATE TABLE IF NOT EXISTS admins (
  id SERIAL PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(255) NOT NULL,
  role VARCHAR(50) NOT NULL DEFAULT 'admin',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS centers (
  id SERIAL PRIMARY KEY,
  center_name VARCHAR(255) NOT NULL UNIQUE,
  center_code VARCHAR(255) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessions (
  id UUID PRIMARY KEY,
  center_name VARCHAR(255) NOT NULL,
  center_code VARCHAR(255) NOT NULL,
  class_name VARCHAR(255),
  sessio_date DATE,
  term VARCHAR(50),
  present_learners INTEGER,
  total_in_class INTEGER,
  total_learner_percentage DECIMAL(5,2),
  notes TEXT,
  goals TEXT,
  follow_up TEXT,
  tracking_progress INTEGER,
  tracking_progress_target INTEGER,
  tracking_progress_outcome VARCHAR(50),
  tracking_accuracy INTEGER,
  tracking_accuracy_target INTEGER,
  tracking_accuracy_outcome VARCHAR(50),
  groupings JSONB,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

