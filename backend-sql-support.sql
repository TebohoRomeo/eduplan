-- Admin-only session lookup
SELECT s.*
FROM sessions s
ORDER BY s.sessio_date DESC, s.created_at DESC;

-- Center-scoped session lookup for existing center login flow
SELECT s.*
FROM sessions s
WHERE s.center_name = :center_name
ORDER BY s.sessio_date DESC, s.created_at DESC;

-- Admin authentication query
SELECT id, email, full_name, role
FROM admins
WHERE email = :email;

-- Optional table index to speed up admin queries
CREATE INDEX IF NOT EXISTS idx_sessions_center_name_date
ON sessions (center_name, sessio_date DESC);
